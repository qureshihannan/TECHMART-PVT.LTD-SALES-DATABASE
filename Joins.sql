		# JOINS 

# 1. Which customers have placed orders?

select c.customerID , c.customer_name, 
o.orderID , o.order_date , o.order_status 
from customers c
inner join orders o
on c.customerID = o.customerID;

# 2. Which customers have never placed an order?

select c.customerID , c.customer_name, o.orderID  
from customers c
left join orders o
on c.customerID = o.customerID
where o.orderID is null;

# 3. which products have been sold

select p.productID , p.product_name , 
od.orderID , od.quantity , od.unit_price
from products p 
inner join orderdetails od
on p.productID = od.productID;

# 4. Show product name, quantity and total amount for every order detail

#	Total Amount = Quantity × Unit Price

select p.product_name , od.orderID ,
 od.quantity , od.unit_price , 
 (od.quantity * od.unit_price) as total_amount
 from products p
 inner join orderdetails od
on p.productID = od.productID;

# 5. Show customer name, order ID and payment details

		# multiple joins
        
select c.customer_name,
o.orderID , o.order_date,
pay.payment_method , pay.payment_amount , pay.payment_status
from Customers c
inner join Orders o
    on c.customerID = o.customerID
INNER JOIN Payments pay
    ON o.orderID = pay.orderID;
    
# 6. Show complete product sales information

# multiple joins
    
select c.customer_name , o.orderID , p.product_name,
od.quantity , od.unit_price , od.quantity * od.unit_price AS total_amount
from Customers c
inner join Orders o
    ON c.customerID = o.customerID
inner join OrderDetails od
    ON o.orderID = od.orderID
inner join Products p
    ON od.productID = p.productID;

# 7. What is the total revenue generated by each customer?

# join + aggregate + group by 

select c.customerID , c.customer_name , 
sum(od.quantity * od.unit_price) as total_revenue
from customers c 
join orders o 
on c.customerID = o.customerID
join orderdetails od
on o.orderID = od.orderID 
group by c.customerID , c.customer_name;

# 8. Which product categories generated the highest revenue?

select p.productID ,  p.product_name , 
 sum(od.quantity * od.unit_price) as total_revenue
 from products p
 inner join orderdetails od
on p.productID = od.productID 
group by p.productID ,  p.product_name
order by total_revenue desc;





